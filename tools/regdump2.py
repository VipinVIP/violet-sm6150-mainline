import mmap,os,struct,sys
# explicit-offset dump of gpucc (known-implemented registers only)
OFFS=[0x0,0x4,0x8,0xc,0x10,0x14,0x18,0x1c,0x20,0x24,0x28,0x100,0x104,0x108,0x10c,0x110,0x114,0x118,0x11c,0x120,0x124,0x128,
 0x1000,0x1004,0x1008,0x100c,0x1010,0x101c,0x1024,0x1028,0x1054,0x1064,0x1068,0x106c,0x1070,0x1078,0x107c,0x108c,0x1090,0x1098,0x109c,0x10a0,0x10a4,0x10a8,0x111c,0x1120,0x1540,0x5000,0x7008]
fd=os.open("/dev/mem",os.O_RDONLY|os.O_SYNC)
m=mmap.mmap(fd,0x9000,mmap.MAP_SHARED,mmap.PROT_READ,offset=0x5090000)
out=open(sys.argv[1],"w")
for o in OFFS:
    out.write("%04x %08x\n"%(o,struct.unpack("<I",m[o:o+4])[0])); out.flush()
