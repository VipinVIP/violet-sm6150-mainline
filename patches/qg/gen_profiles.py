#!/usr/bin/env python3
"""Generate violet-qg-profiles.h from the vendor LC_M6300_*_FG.dtsi battery profiles.

usage: gen_profiles.py <dir with the three dtsi> > violet-qg-profiles.h
Only the tables the downstream qg driver actually consults are emitted:
  v1 = charging SoC-OCV, v2 = discharging SoC-OCV (qg-profile-lib.c lookup_soc_ocv),
  fcc2 = full charge capacity vs temperature.
"""
import re, sys, glob, os

def nums(s):
    return [int(x) for x in re.findall(r'-?\d+', s.replace('(', ' ').replace(')', ' '))]

def lut(text, name):
    m = re.search(r'qcom,%s\s*\{(.*?)\n\t\};' % re.escape(name), text, re.S)
    assert m, name
    body = m.group(1)
    col = nums(re.search(r'lut-col-legend\s*=\s*<(.*?)>;', body, re.S).group(1))
    rowm = re.search(r'lut-row-legend\s*=\s*(.*?);', body, re.S)
    row = nums(rowm.group(1)) if rowm else None
    data = nums(re.search(r'lut-data\s*=\s*(.*?);', body, re.S).group(1))
    return col, row, data

def main(d):
    out = ['/* SPDX-License-Identifier: GPL-2.0 */',
           '/* Generated by gen_profiles.py from the vendor LC_M6300_*_FG.dtsi. Do not edit. */', '']
    names = []
    for f in sorted(glob.glob(os.path.join(d, 'LC_M6300_*_FG.dtsi'))):
        t = open(f).read()
        ident = re.search(r'qcom,batt-id-kohm\s*=\s*<(\d+)>', t).group(1)
        btype = re.search(r'qcom,battery-type\s*=\s*"(.*?)"', t).group(1)
        vmax = int(re.search(r'qcom,max-voltage-uv\s*=\s*<(\d+)>', t).group(1))
        short = re.search(r'LC_M6300_([A-Za-z]+)', f).group(1).lower()
        names.append((short, ident, btype, vmax))
        for tab in ('pc-temp-v1-lut', 'pc-temp-v2-lut'):
            col, row, data = lut(t, tab)
            n = len(col)
            assert len(data) == n * len(row), (f, tab, len(data), n, len(row))
            tag = 'v1' if 'v1' in tab else 'v2'
            out.append('static const s16 qgp_%s_%s_temp[] = { %s };' % (short, tag, ', '.join(map(str, col))))
            out.append('static const u16 qgp_%s_%s_pc[] = { %s };' % (short, tag, ', '.join(map(str, row))))
            out.append('static const u16 qgp_%s_%s_ocv[%d][%d] = {' % (short, tag, len(row), n))
            for r in range(len(row)):
                out.append('\t{ %s },' % ', '.join(map(str, data[r*n:(r+1)*n])))
            out.append('};')
        col, _, data = lut(t, 'fcc2-temp-lut')
        out.append('static const s16 qgp_%s_fcc_temp[] = { %s };' % (short, ', '.join(map(str, col))))
        out.append('static const u16 qgp_%s_fcc_mah[] = { %s };' % (short, ', '.join(map(str, data))))
        out.append('')
    out.append('struct qg_profile {')
    out.append('\tconst char *name; const char *type; unsigned int id_kohm, vmax_uv;')
    out.append('\tint n_t1, n_r1, n_t2, n_r2, n_tf;')
    out.append('\tconst s16 *t1; const u16 *pc1; const u16 *ocv1;')
    out.append('\tconst s16 *t2; const u16 *pc2; const u16 *ocv2;')
    out.append('\tconst s16 *tf; const u16 *fcc;')
    out.append('};')
    out.append('static const struct qg_profile qg_profiles[] = {')
    for short, ident, btype, vmax in names:
        s = 'qgp_' + short
        out.append('\t{ "%s", "%s", %s, %d, ARRAY_SIZE(%s_v1_temp), ARRAY_SIZE(%s_v1_pc), ARRAY_SIZE(%s_v2_temp), ARRAY_SIZE(%s_v2_pc), ARRAY_SIZE(%s_fcc_temp),'
                   % (short, btype, ident, vmax, s, s, s, s, s))
        out.append('\t  %s_v1_temp, %s_v1_pc, (const u16 *)%s_v1_ocv, %s_v2_temp, %s_v2_pc, (const u16 *)%s_v2_ocv, %s_fcc_temp, %s_fcc_mah },'
                   % ((s,) * 8))
    out.append('};')
    print('\n'.join(out))

main(sys.argv[1])
